export function findSmartIslamicAnswer(query: string): string | null {
  const normalized = query.toLowerCase().replace(/[\u064B-\u065F\u0670]/g, '').trim();
  
  for (const item of ISLAMIC_KNOWLEDGE_BASE) {
    const match = item.keywords.some((kw) => normalized.includes(kw.toLowerCase()));
    if (match) {
      return item.response;
    }
  }

  return null;
}
